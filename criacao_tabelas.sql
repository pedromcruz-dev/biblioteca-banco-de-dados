CREATE SCHEMA IF NOT EXISTS TRABALHO;

CREATE TABLE TRABALHO.TIPO (
	COD_TIPO		 	INT GENERATED ALWAYS AS IDENTITY,
	DESC_TIPO			VARCHAR(20)		NOT NULL,
	PRAZO				INT				NOT NULL,
	
	CONSTRAINT PK_TIPO PRIMARY KEY (COD_TIPO)
);

CREATE TABLE TRABALHO.PESSOA (
	COD_PESSOA			INT GENERATED ALWAYS AS IDENTITY,
	NOME_PESSOA			VARCHAR(150)	NOT NULL,
	RUA					VARCHAR(150) 	NOT NULL,
	NUMERO				VARCHAR(20)		NOT NULL,
	COD_TIPO			INT 			NOT NULL,
	
	CONSTRAINT PK_PESSOA PRIMARY KEY (COD_PESSOA),
	CONSTRAINT FK_COD_TIPO_PESSOA
		FOREIGN KEY (COD_TIPO) REFERENCES TRABALHO.TIPO (COD_TIPO)
);

CREATE TABLE TRABALHO.TELEFONE_PESSOA (
	COD_PESSOA			INT				NOT NULL,
	TELEFONE			VARCHAR(11)		NOT NULL,

	CONSTRAINT PK_TELEFONE_PESSOA
		PRIMARY KEY (COD_PESSOA, TELEFONE),

	CONSTRAINT FK_TELEFONE_PESSOA
		FOREIGN KEY (COD_PESSOA) REFERENCES TRABALHO.PESSOA (COD_PESSOA)
);

CREATE TABLE TRABALHO.AUTOR (
	COD_AUTOR			INT GENERATED ALWAYS AS IDENTITY,
	NOME_AUTOR			VARCHAR(150)	NOT NULL,

	CONSTRAINT PK_AUTOR PRIMARY KEY (COD_AUTOR)
);

CREATE TABLE TRABALHO.AREA (
	COD_AREA			INT GENERATED ALWAYS AS IDENTITY,
	DESC_AREA			VARCHAR(150)	NOT NULL,

	CONSTRAINT PK_AREA PRIMARY KEY (COD_AREA)
);

CREATE TABLE TRABALHO.TEMA (
	COD_TEMA			INT GENERATED ALWAYS AS IDENTITY,
	DESC_TEMA			VARCHAR(150)	NOT NULL,
	COD_AREA			INT				NOT NULL,

	CONSTRAINT PK_TEMA PRIMARY KEY (COD_TEMA),

	CONSTRAINT FK_TEMA_AREA
		FOREIGN KEY (COD_AREA) REFERENCES TRABALHO.AREA (COD_AREA)
);

CREATE TABLE TRABALHO.EDITORA (
	CNPJ_EDITORA		VARCHAR(14)		NOT NULL,
	NOME_EDITORA		VARCHAR(250)	NOT NULL,

	CONSTRAINT PK_EDITORA PRIMARY KEY (CNPJ_EDITORA)
);

CREATE TABLE TRABALHO.EMAIL_EDITORA (
	CNPJ_EDITORA		VARCHAR(14)		NOT NULL,
	EMAIL_EDITORA		VARCHAR(254)	NOT NULL,

	CONSTRAINT PK_EMAIL_EDITORA PRIMARY KEY (CNPJ_EDITORA, EMAIL_EDITORA),

	CONSTRAINT FK_EMAIL_EDITORA
		FOREIGN KEY (CNPJ_EDITORA) REFERENCES TRABALHO.EDITORA (CNPJ_EDITORA)
);

CREATE TABLE TRABALHO.LIVRO (
	ISBN				VARCHAR(13)		NOT NULL,
	TITULO				VARCHAR(100)	NOT NULL,
	ANO_PUBLICACAO		INT				NOT NULL,
	COD_TEMA			INT				NOT NULL,
	CNPJ_EDITORA		VARCHAR(14)		NOT NULL,

	CONSTRAINT PK_LIVRO PRIMARY KEY (ISBN),

	CONSTRAINT FK_LIVRO_TEMA FOREIGN KEY (COD_TEMA)
		REFERENCES TRABALHO.TEMA (COD_TEMA),

	CONSTRAINT FK_LIVRO_EDITORA FOREIGN KEY (CNPJ_EDITORA)
		REFERENCES TRABALHO.EDITORA (CNPJ_EDITORA)
);

CREATE TABLE TRABALHO.EXEMPLAR (
	ISBN				VARCHAR(13)		NOT NULL,
	NUMERO_EXEMPLAR		INT				NOT NULL,
	SITUACAO			VARCHAR(1)		NOT NULL DEFAULT 'D',

	CONSTRAINT CK_SITUACAO CHECK(SITUACAO IN('D', 'E')),

	CONSTRAINT PK_EXEMPLAR PRIMARY KEY (ISBN, NUMERO_EXEMPLAR),

	CONSTRAINT FK_EXEMPLAR_LIVRO FOREIGN KEY (ISBN)
		REFERENCES TRABALHO.LIVRO (ISBN)
);

CREATE TABLE TRABALHO.EMPRESTA (
	ISBN				VARCHAR(13)		NOT NULL,
	NUMERO_EXEMPLAR		INT				NOT NULL,
	COD_PESSOA			INT				NOT NULL,
	DATA_EMPRESTIMO		DATE			NOT NULL,
	DATA_DEVOLUCAO		DATE,
	MULTA_ATRASO		NUMERIC(10,2)	NOT NULL DEFAULT 0.00,

	CONSTRAINT PK_EMPRESTA PRIMARY KEY (ISBN, NUMERO_EXEMPLAR, COD_PESSOA),

	CONSTRAINT FK_EMPRESTA_LIVRO FOREIGN KEY (ISBN)
		REFERENCES TRABALHO.LIVRO (ISBN),

	CONSTRAINT FK_EMPRESTA_EXEMPLAR FOREIGN KEY (ISBN, NUMERO_EXEMPLAR)
		REFERENCES TRABALHO.EXEMPLAR (ISBN, NUMERO_EXEMPLAR),

	CONSTRAINT FK_EMPRESTA_PESSOA FOREIGN KEY (COD_PESSOA)
		REFERENCES TRABALHO.PESSOA (COD_PESSOA)
);

CREATE TABLE TRABALHO.ESCREVE (
	COD_AUTOR 			INT 			NOT NULL, 
	ISBN 				VARCHAR(13) 	NOT NULL,

	CONSTRAINT PK_ESCREVE PRIMARY KEY (COD_AUTOR, ISBN),

	CONSTRAINT FK_ESCREVE_AUTOR FOREIGN KEY (COD_AUTOR)
		REFERENCES TRABALHO.AUTOR (COD_AUTOR),

	CONSTRAINT FK_ESCREVE_LIVRO FOREIGN KEY (ISBN)
		REFERENCES TRABALHO.LIVRO (ISBN)
);